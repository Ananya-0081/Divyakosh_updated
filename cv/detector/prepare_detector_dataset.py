"""
cv/detector/prepare_detector_dataset.py

Builds a single-class YOLOv8 banknote detection dataset from two sources:

  Source A — Synthetic composites (primary, masked):
    • black_box/10, 20, 50, 100, 200  (22,920 masked note images)
    • data_clean/train/500/SYN_500_*  (₹500 fallback, black-background,
                                       1,184 mask-eligible images)
    Scenes are generated by compositing 1–3 notes onto a plain canvas using
    binary masking. YOLO labels are derived from the visible note bounding
    boxes. This provides tight, accurate localization supervision.

  Source B — Real-camera full-frame (weak supervision):
    • data_clean/train/500/RC_SRC_*   (28 real captures; 21 pass QC)
    These images fill the entire frame with a banknote, so the YOLO label
    is assigned as a full-image box (cx=0.5, cy=0.5, w=1.0, h=1.0).

    ⚠ WEAK SUPERVISION NOTE: Full-frame bbox labels do not teach the model
      where the note boundary is within the image. They provide correct
      positive supervision (a note IS present) but imprecise localization.
      This is acceptable for a binary presence gate but not for precise
      counting or cropping. Only 21 images receive this treatment.

  Negatives — empty black canvases (YOLO label = empty .txt file).

Dataset layout (created at cv/detector/yolo_dataset/):
    data.yaml
    images/{train,val,test}/
    labels/{train,val,test}/

Split: 70 / 15 / 15  (train / val / test)
No scene-level leakage: scenes are assigned to splits before generation;
the same synthetic scene never appears in more than one split.

Run:
    cd cv
    .venv/Scripts/python detector/prepare_detector_dataset.py
    # Add --scenes N to change total synthetic scene count (default 4500)
    # Add --seed N to change random seed (default 42)
"""

from __future__ import annotations

import argparse
import json
import random
import shutil
from collections import Counter, defaultdict
from pathlib import Path
from typing import Optional

import cv2
import numpy as np
from tqdm import tqdm

# ---------------------------------------------------------------------------
# Paths (relative to cv/ project root)
# ---------------------------------------------------------------------------

_THIS_FILE = Path(__file__).resolve()
_PROJECT_ROOT = _THIS_FILE.parent.parent          # cv/
_DETECTOR_DIR = _THIS_FILE.parent                 # cv/detector/
_OUT_DIR = _DETECTOR_DIR / "yolo_dataset"

_BLACK_BOX_DIR = _PROJECT_ROOT / "synthetic_dataset" / "black_box"
_DATA_500_DIR  = _PROJECT_ROOT / "data_clean" / "train" / "500"
_MODELS_DIR    = _PROJECT_ROOT / "models"

# QC thresholds for ₹500 fallback images
_SYN500_BLACK_BG_MIN   = 0.50   # must be at least 50% black background
_SYN500_COVERAGE_MIN   = 0.08   # note must cover at least 8% of frame
_RC_COVERAGE_MIN       = 0.40   # real-camera: note must cover 40%
_RC_LAPLACIAN_MIN      = 30.0   # real-camera: Laplacian variance (blur check)

# Supported denominations (for reporting)
SUPPORTED_DENOMS = ["10", "20", "50", "100", "200", "500"]


# ---------------------------------------------------------------------------
# Image quality checks
# ---------------------------------------------------------------------------

def _image_stats(img_bgr: np.ndarray) -> dict:
    gray = cv2.cvtColor(img_bgr, cv2.COLOR_BGR2GRAY)
    black_pct = (gray < 15).sum() / gray.size
    coverage  = ((gray > 15) & (gray < 245)).sum() / gray.size
    lap_var   = float(cv2.Laplacian(gray, cv2.CV_64F).var())
    return {"black_bg": black_pct, "coverage": coverage, "lap_var": lap_var}


def _passes_syn500_qc(stats: dict) -> bool:
    return stats["black_bg"] >= _SYN500_BLACK_BG_MIN and stats["coverage"] >= _SYN500_COVERAGE_MIN


def _passes_rc_qc(stats: dict) -> bool:
    return stats["coverage"] >= _RC_COVERAGE_MIN and stats["lap_var"] >= _RC_LAPLACIAN_MIN


# ---------------------------------------------------------------------------
# Note extraction from black-background images
# ---------------------------------------------------------------------------

def extract_note_from_blackbg(img_bgr: np.ndarray) -> tuple[Optional[np.ndarray], Optional[np.ndarray]]:
    """
    Extract the note and its binary mask from a black-background image.
    Returns (cropped_note_bgr, cropped_mask) or (None, None) if extraction fails.
    """
    gray = cv2.cvtColor(img_bgr, cv2.COLOR_BGR2GRAY)
    _, mask = cv2.threshold(gray, 15, 255, cv2.THRESH_BINARY)
    kernel = np.ones((5, 5), np.uint8)
    mask = cv2.morphologyEx(mask, cv2.MORPH_OPEN, kernel)
    mask = cv2.morphologyEx(mask, cv2.MORPH_CLOSE, kernel)

    contours, _ = cv2.findContours(mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
    if not contours:
        return None, None
    largest = max(contours, key=cv2.contourArea)
    if cv2.contourArea(largest) < 500:
        return None, None

    x, y, w, h = cv2.boundingRect(largest)
    return img_bgr[y:y+h, x:x+w], mask[y:y+h, x:x+w]


def _transform_note(img: np.ndarray, mask: np.ndarray, canvas_hw: tuple[int, int]) -> tuple[np.ndarray, np.ndarray]:
    """Random rotate + scale + translate. Returns (transformed_img, transformed_mask) on canvas."""
    ch, cw = canvas_hw
    h, w   = img.shape[:2]

    scale  = random.uniform(0.4, 1.1)
    new_w, new_h = int(w * scale), int(h * scale)
    if new_w < 10 or new_h < 10:
        return np.zeros((ch, cw, 3), np.uint8), np.zeros((ch, cw), np.uint8)

    img  = cv2.resize(img,  (new_w, new_h))
    mask = cv2.resize(mask, (new_w, new_h))

    angle  = random.uniform(0, 360)
    center = (new_w // 2, new_h // 2)
    M      = cv2.getRotationMatrix2D(center, angle, 1.0)
    cos, sin = abs(M[0, 0]), abs(M[0, 1])
    rot_w = int(new_h * sin + new_w * cos)
    rot_h = int(new_h * cos + new_w * sin)
    M[0, 2] += rot_w / 2 - center[0]
    M[1, 2] += rot_h / 2 - center[1]

    img  = cv2.warpAffine(img,  M, (rot_w, rot_h), flags=cv2.INTER_LINEAR,  borderValue=(0, 0, 0))
    mask = cv2.warpAffine(mask, M, (rot_w, rot_h), flags=cv2.INTER_NEAREST, borderValue=0)

    # Random placement (allow partial cutoff)
    sx = random.randint(int(-rot_w * 0.2), int(cw - rot_w * 0.8))
    sy = random.randint(int(-rot_h * 0.2), int(ch - rot_h * 0.8))

    canvas_img  = np.zeros((ch, cw, 3), np.uint8)
    canvas_mask = np.zeros((ch, cw),    np.uint8)
    x1, y1 = max(0, sx), max(0, sy)
    x2, y2 = min(cw, sx + rot_w), min(ch, sy + rot_h)
    ix1, iy1 = x1 - sx, y1 - sy
    ix2, iy2 = ix1 + (x2 - x1), iy1 + (y2 - y1)
    if x1 < x2 and y1 < y2:
        canvas_img[y1:y2, x1:x2]  = img[iy1:iy2, ix1:ix2]
        canvas_mask[y1:y2, x1:x2] = mask[iy1:iy2, ix1:ix2]
    return canvas_img, canvas_mask


def _add_noise(img: np.ndarray) -> np.ndarray:
    if random.random() < 0.35:
        img = cv2.GaussianBlur(img, (3, 3), 0)
    if random.random() < 0.35:
        noise = np.random.normal(0, 6, img.shape).astype(np.int16)
        img = np.clip(img.astype(np.int16) + noise, 0, 255).astype(np.uint8)
    return img


def generate_scene(
    source_pool: list[Path],
    num_notes: int,
    canvas_hw: tuple[int, int] = (480, 640),
) -> tuple[np.ndarray, list[str]]:
    """
    Generate a synthetic scene with `num_notes` banknotes composited.
    Returns (canvas_bgr, yolo_labels).
    If num_notes == 0, returns a plain black negative canvas with no labels.
    """
    ch, cw = canvas_hw
    canvas = np.zeros((ch, cw, 3), np.uint8)
    if num_notes == 0:
        return canvas, []

    notes_data: list[tuple[np.ndarray, np.ndarray]] = []
    for _ in range(num_notes):
        src_path = random.choice(source_pool)
        raw = cv2.imread(str(src_path))
        if raw is None:
            continue
        note, mask = extract_note_from_blackbg(raw)
        if note is None:
            continue
        t_img, t_mask = _transform_note(note, mask, canvas_hw)
        notes_data.append((t_img, t_mask))

    # Composite bottom-to-top
    for img, mask in notes_data:
        idx = mask > 127
        canvas[idx] = img[idx]

    # YOLO labels: visible bounding box of each note
    labels: list[str] = []
    for i, (_, mask_i) in enumerate(notes_data):
        visible = mask_i.copy()
        for j in range(i + 1, len(notes_data)):
            visible[notes_data[j][1] > 127] = 0
        contours, _ = cv2.findContours(visible, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
        if contours and cv2.countNonZero(visible) > 300:
            all_pts = np.concatenate(contours)
            x, y, w, h = cv2.boundingRect(all_pts)
            xc, yc = (x + w / 2) / cw, (y + h / 2) / ch
            nw, nh = w / cw, h / ch
            labels.append(f"0 {xc:.6f} {yc:.6f} {nw:.6f} {nh:.6f}")

    canvas = _add_noise(canvas)
    return canvas, labels


# ---------------------------------------------------------------------------
# Source pool loading
# ---------------------------------------------------------------------------

def load_source_pool(verbose: bool = True) -> tuple[list[Path], dict]:
    """
    Collect all mask-eligible note images:
      - black_box/{10,20,50,100,200}
      - data_clean/train/500/SYN_500_* that pass QC

    Returns (pool, report_dict).
    """
    pool: list[Path] = []
    report: dict[str, dict] = {}

    # black_box (5 denominations)
    bb_total = 0
    for denom in ["10", "20", "50", "100", "200"]:
        ddir = _BLACK_BOX_DIR / denom
        paths = sorted(p for p in ddir.glob("*") if p.suffix.lower() in {".jpg", ".jpeg", ".png"})
        pool.extend(paths)
        report[f"black_box/{denom}"] = {"count": len(paths), "source": "mask-based"}
        bb_total += len(paths)
        if verbose:
            print(f"  black_box/{denom}: {len(paths):,} images (mask-based)")

    # ₹500 SYN fallback from data_clean/train/500/
    syn500_paths = sorted(p for p in _DATA_500_DIR.glob("SYN_500_*.jpg"))
    syn500_pass = 0
    for p in tqdm(syn500_paths, desc="  QC ₹500 SYN_500", leave=False, disable=not verbose):
        img = cv2.imread(str(p))
        if img is None:
            continue
        stats = _image_stats(img)
        if _passes_syn500_qc(stats):
            pool.append(p)
            syn500_pass += 1
    report["data_clean/500/SYN"] = {
        "count": syn500_pass,
        "total_scanned": len(syn500_paths),
        "source": "mask-based (Rs500 fallback)",
        "supervision": "tight bbox via mask extraction",
    }
    if verbose:
        print(f"  Rs.500 SYN_500_* fallback: {syn500_pass:,}/{len(syn500_paths):,} pass QC (mask-based)")

    # Rs.500 RC_SRC (real camera) — collected separately, not in pool (handled later)
    rc_paths = sorted(p for p in _DATA_500_DIR.glob("RC_SRC_*.jpg"))
    rc_pass: list[Path] = []
    for p in rc_paths:
        img = cv2.imread(str(p))
        if img is None:
            continue
        if _passes_rc_qc(_image_stats(img)):
            rc_pass.append(p)
    report["data_clean/500/RC_SRC"] = {
        "count": len(rc_pass),
        "total_scanned": len(rc_paths),
        "source": "full-frame bbox (Rs500 real camera)",
        "supervision": "[WEAK] full-image bbox, 21 images only",
    }
    if verbose:
        print(f"  Rs.500 RC_SRC_* real camera: {len(rc_pass):,}/{len(rc_paths):,} pass QC (full-frame bbox [WEAK])")

    if verbose:
        print(f"\n  Total mask-eligible pool: {len(pool):,} images")
    return pool, report, rc_pass


# ---------------------------------------------------------------------------
# Dataset builder
# ---------------------------------------------------------------------------

def build_dataset(
    total_scenes: int = 4500,
    seed: int = 42,
    canvas_hw: tuple[int, int] = (480, 640),
    split_ratios: tuple[float, float, float] = (0.70, 0.15, 0.15),
    negative_fraction: float = 0.10,
    verbose: bool = True,
) -> dict:
    """
    Build the complete YOLOv8 banknote detector dataset.
    Returns a stats dict for reporting.
    """
    random.seed(seed)
    np.random.seed(seed)

    if verbose:
        print("=" * 60)
        print("DivyaKosh — Banknote Detector Dataset Builder")
        print("=" * 60)

    # ------------------------------------------------------------------
    # 1. Load source pool
    # ------------------------------------------------------------------
    if verbose:
        print("\n[1/5] Loading source images...")
    source_pool, pool_report, rc_pass = load_source_pool(verbose=verbose)

    if len(source_pool) < 10:
        raise RuntimeError("Source pool too small. Check black_box/ and data_clean/train/500/ paths.")

    # ------------------------------------------------------------------
    # 2. Plan scenes
    # ------------------------------------------------------------------
    n_neg  = int(total_scenes * negative_fraction)
    n_pos  = total_scenes - n_neg
    n_s1   = int(n_pos * 0.45)   # single-note
    n_s2   = int(n_pos * 0.40)   # double-note
    n_s3   = n_pos - n_s1 - n_s2 # triple-note

    scene_plan = ([1]*n_s1) + ([2]*n_s2) + ([3]*n_s3) + ([0]*n_neg)
    random.shuffle(scene_plan)

    tr_r, va_r, te_r = split_ratios
    n_tr = int(total_scenes * tr_r)
    n_va = int(total_scenes * va_r)
    n_te = total_scenes - n_tr - n_va
    split_labels = (["train"]*n_tr) + (["val"]*n_va) + (["test"]*n_te)
    random.shuffle(split_labels)

    if verbose:
        print(f"\n[2/5] Scene plan:")
        print(f"  Single-note  : {n_s1:,}")
        print(f"  Double-note  : {n_s2:,}")
        print(f"  Triple-note  : {n_s3:,}")
        print(f"  Negatives    : {n_neg:,}")
        print(f"  Total        : {total_scenes:,}")
        print(f"  Train/Val/Test: {n_tr}/{n_va}/{n_te}")

    # ------------------------------------------------------------------
    # 3. Create output directories
    # ------------------------------------------------------------------
    for split in ["train", "val", "test"]:
        (_OUT_DIR / "images" / split).mkdir(parents=True, exist_ok=True)
        (_OUT_DIR / "labels" / split).mkdir(parents=True, exist_ok=True)

    # ------------------------------------------------------------------
    # 4. Generate scenes
    # ------------------------------------------------------------------
    if verbose:
        print("\n[3/5] Generating synthetic scenes...")

    split_counts: dict[str, Counter] = {
        "train": Counter(), "val": Counter(), "test": Counter()
    }
    for idx, (num_notes, split) in enumerate(
        tqdm(zip(scene_plan, split_labels), total=total_scenes, desc="  scenes", disable=not verbose)
    ):
        img, labels = generate_scene(source_pool, num_notes, canvas_hw)
        stem = f"scene_{idx:05d}"
        cv2.imwrite(str(_OUT_DIR / "images" / split / f"{stem}.jpg"), img,
                    [cv2.IMWRITE_JPEG_QUALITY, 90])
        lbl_path = _OUT_DIR / "labels" / split / f"{stem}.txt"
        lbl_path.write_text("\n".join(labels))

        tag = f"{num_notes}note" if num_notes > 0 else "negative"
        split_counts[split][tag] += 1

    # ------------------------------------------------------------------
    # 5. Add RC_SRC full-frame images (train only — too few to split)
    # ------------------------------------------------------------------
    if verbose:
        print(f"\n[4/5] Adding {len(rc_pass)} RC_SRC full-frame images to train...")

    rc_added = 0
    for p in rc_pass:
        img = cv2.imread(str(p))
        if img is None:
            continue
        dst_img = _OUT_DIR / "images" / "train" / f"rc_{p.name}"
        dst_lbl = _OUT_DIR / "labels" / "train" / f"rc_{p.stem}.txt"
        shutil.copy2(p, dst_img)
        # Full-frame bbox: class=0, cx=0.5, cy=0.5, w=1.0, h=1.0
        dst_lbl.write_text("0 0.500000 0.500000 1.000000 1.000000\n")
        split_counts["train"]["rc_fullframe"] += 1
        rc_added += 1

    # ------------------------------------------------------------------
    # 6. Write data.yaml
    # ------------------------------------------------------------------
    yaml_content = (
        f"# DivyaKosh banknote detector dataset\n"
        f"# Generated by detector/prepare_detector_dataset.py\n"
        f"# Single class: banknote (presence gate only — denomination handled by MobileNetV3)\n\n"
        f"path: {_OUT_DIR.as_posix()}\n"
        f"train: images/train\n"
        f"val:   images/val\n"
        f"test:  images/test\n\n"
        f"nc: 1\n"
        f"names:\n"
        f"  0: banknote\n"
    )
    (_OUT_DIR / "data.yaml").write_text(yaml_content)

    # ------------------------------------------------------------------
    # 7. Final report
    # ------------------------------------------------------------------
    stats = {
        "source_pool": pool_report,
        "scene_plan":  {"single": n_s1, "double": n_s2, "triple": n_s3, "negative": n_neg, "total": total_scenes},
        "rc_src_added": rc_added,
        "splits": {k: dict(v) for k, v in split_counts.items()},
        "output_dir": str(_OUT_DIR),
    }
    (_OUT_DIR / "dataset_report.json").write_text(json.dumps(stats, indent=2))

    if verbose:
        print("\n[5/5] Dataset statistics:")
        for split in ["train", "val", "test"]:
            imgs = list((_OUT_DIR / "images" / split).glob("*.jpg"))
            lbls = list((_OUT_DIR / "labels" / split).glob("*.txt"))
            non_empty = sum(1 for l in lbls if l.read_text().strip())
            empty_lbl = len(lbls) - non_empty
            print(f"\n  {split.upper()} ({len(imgs)} images, {len(lbls)} labels):")
            for tag, cnt in sorted(split_counts[split].items()):
                print(f"    {tag:20s}: {cnt:,}")
            print(f"    {'non-empty labels':20s}: {non_empty:,}")
            print(f"    {'empty labels (neg)':20s}: {empty_lbl:,}")

        print(f"\n  Output: {_OUT_DIR}")
        print(f"  data.yaml written.")
        print("\n  [SUPERVISION NOTE]")
        print(f"     {rc_added} RC_SRC images have full-image bbox labels (weak localization).")
        print( "     All other positive images use mask-extracted tight bboxes (strong).")
        print( "     Rs.500 coverage in training is lower than other denominations but")
        print( "     the detector only needs to detect 'banknote present' (1 class).")

    return stats


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def main() -> None:
    parser = argparse.ArgumentParser(
        description="Build YOLOv8n banknote detection dataset for DivyaKosh."
    )
    parser.add_argument("--scenes", type=int, default=4500,
                        help="Total synthetic scenes to generate (default: 4500)")
    parser.add_argument("--seed",   type=int, default=42,
                        help="Random seed (default: 42)")
    parser.add_argument("--canvas", type=str, default="480x640",
                        help="Canvas HxW for synthetic scenes (default: 480x640)")
    parser.add_argument("--clean",  action="store_true",
                        help="Delete existing yolo_dataset/ before building")
    args = parser.parse_args()

    if args.clean and _OUT_DIR.exists():
        print(f"Removing existing {_OUT_DIR} ...")
        shutil.rmtree(_OUT_DIR)

    h, w = [int(x) for x in args.canvas.split("x")]
    build_dataset(
        total_scenes=args.scenes,
        seed=args.seed,
        canvas_hw=(h, w),
    )


if __name__ == "__main__":
    main()

